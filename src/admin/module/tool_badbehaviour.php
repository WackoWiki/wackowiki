	/**
	 * Lookup an IP in Project Honey Pot's http:BL.
	 * Returns a human-readable description string, or empty string on miss.
	 *
	 * Cache: stored in $engine->sess->httpbl[ip] = "127.x.x.x" for 24h.
	 */
	function bb2_httpbl_lookup($engine, $ip): string
	{
		$settings	= bb2_read_settings($engine);
		$key		= $settings['httpbl']['key'] ?? '';

		if (!preg_match('/^[a-z]{12}$/', $key))
		{
			return '';
		}

		// Validate IP (IPv4 only — http:BL doesn't support IPv6)
		if (!filter_var($ip, FILTER_VALIDATE_IP, FILTER_FLAG_IPV4))
		{
			return '';
		}

		$cache = $engine->sess->httpbl ?? [];

		// Cached?
		if (isset($cache[$ip]) && $cache[$ip] !== '')
		{
			$r = $cache[$ip];
		}
		else
		{
			// Reverse octets for http:BL query
			$find	= implode('.', array_reverse(explode('.', $ip)));
			$query	= "{$key}.{$find}.dnsbl.httpbl.org.";
			$resp	= @gethostbynamel($query);

			if (empty($resp))
			{
				$cache[$ip] = '';
				$engine->sess->httpbl = $cache;

				return '';
			}

			$r = $resp[0];
			$cache[$ip] = $r;
			$engine->sess->httpbl = $cache;
		}

		// http:BL response: 127.<activity>.<threat>.<type>
		$parts = explode('.', $r);

		if (count($parts) !== 4 || $parts[0] !== '127')
		{
			return '';
		}

		$activity	= (int)$parts[1];
		$threat		= (int)$parts[2];
		$type		= (int)$parts[3];

		$out = [];

		// Type 0 = known search engine (whitelist candidate)
		if ($type === 0)
		{
			$out[] = 'Search engine (whitelist candidate)';
		}
		// Type bit flags
		if ($type & 1) $out[] = 'Suspicious';
		if ($type & 2) $out[] = 'Harvester';
		if ($type & 4) $out[] = 'Comment spammer';
		if ($type & 7) $out[] = "Threat level {$threat}";
		if ($activity > 0) $out[] = "Age {$activity} days";

		return implode('<br>', $out);
	}

