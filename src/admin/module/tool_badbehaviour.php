		// but we round-trip what's in the file)
		$existing = bb2_read_settings($engine);

		// ===== CUSTOM RULES — JSON-per-line =====
		// Each non-empty line is a JSON object: {"type":"ip","value":"1.2.3.4","action":"block","id":"..."}
		$custom_rules	= [];
		$raw_custom		= (string)($_POST['custom_rules'] ?? '');

		foreach (preg_split('/\r\n|\r|\n/', $raw_custom) as $line)
		{
			$line = trim($line);

			if ($line === '')
			{
				continue;
			}

			$decoded = json_decode($line, true);

			if (is_array($decoded) && isset($decoded['type'], $decoded['action']))
			{
				$custom_rules[] = $decoded;
			}
			else
			{
				return [
					'success'  => false,
					'error'    => 'Invalid JSON in custom_rules: ' . htmlspecialchars(substr($line, 0, 80)),
					'payload'  => $_POST,
				];
			}
		}

		// ===== BODY SCAN — one field name per line =====
		$body_scan_skip_fields = array_filter(
			array_map('trim', preg_split('/\r\n|\r|\n/', (string)($_POST['body_scan_skip_fields'] ?? '')))
			);

		$new_settings = [
			// ===== CORE =====
			'logging'                    => !empty($_POST['logging']),
			'verbose'                    => !empty($_POST['verbose']),
			'strict'                     => !empty($_POST['strict']),
			'offsite_forms'              => !empty($_POST['offsite_forms']),

