				'enabled'   => !empty($_POST['reverse_proxy']),
				'header'    => $_POST['reverse_proxy_header'] ?? 'X-Forwarded-For',
				'addresses' => array_filter(array_map('trim', explode("\n", $_POST['reverse_proxy_addresses'] ?? ''))),
			],

			// ===== HTTP:BL =====
			'httpbl' => [
				'key'    => preg_match('/^[a-z]{12}$/', $_POST['httpbl_key'] ?? '') ? $_POST['httpbl_key'] : '',
				'threat' => max(0, min(255, (int)($_POST['httpbl_threat'] ?? 25))),
				'maxage' => max(0, (int)($_POST['httpbl_maxage'] ?? 30)),
			],

			// ===== DNSBL =====
			'dnsbl' => [
				'enabled' => !empty($_POST['dnsbl_enabled']),
				'lists'   => array_filter(array_map('trim', explode("\n", $_POST['dnsbl_lists'] ?? ''))),
			],

			// ===== AI CRAWLERS =====
			'ai_crawlers' => [
				'allowed'          => array_filter(array_map('trim', explode("\n", $_POST['allowed_ai_crawlers'] ?? ''))),
				'block_unverified' => !empty($_POST['block_unverified_ai']),
				'strict'           => !empty($_POST['strict_ai']),
			],

			// ===== BOT CATEGORIES =====
			'bot_categories' => [
				'blocked' => $existing['bot_categories']['blocked'] ?? ['malicious'],
			],

			// ===== RATE LIMITS =====
			'rate_limits' => [
				'enabled'    => !empty($_POST['rate_limit_enabled']),
				'global'     => [
					'requests' => max(1, (int)($_POST['rate_global_requests'] ?? 1000)),
					'window'   => max(1, (int)($_POST['rate_global_window']   ?? 3600)),
				],
				'per_minute' => [
					'requests' => max(1, (int)($_POST['rate_per_minute_requests'] ?? 60)),
					'window'   => max(1, (int)($_POST['rate_per_minute_window']   ?? 60)),
				],
				'post'       => [
					'requests' => max(1, (int)($_POST['rate_post_requests'] ?? 30)),
					'window'   => max(1, (int)($_POST['rate_post_window']   ?? 3600)),
				],
				'login'      => [
					'requests' => max(1, (int)($_POST['rate_login_requests'] ?? 10)),
					'window'   => max(1, (int)($_POST['rate_login_window']   ?? 900)),
				],
			],

			// ===== CHALLENGE =====
			'challenge' => [
				'enabled'             => !empty($_POST['challenge_enabled']),
				'provider'            => in_array($_POST['challenge_provider'] ?? '', ['builtin', 'hcaptcha', 'recaptcha', 'turnstile'], true)
					? $_POST['challenge_provider']
					: 'builtin',
				'site_key'            => trim($_POST['challenge_site_key'] ?? ''),
				'secret_key'          => trim($_POST['challenge_secret_key'] ?? ''),
