			// ===== CUSTOM RULES =====
			'custom_rules' => $custom_rules,

			// ===== 3.0 FEATURES =====
			'enable_fingerprinting'          => !empty($_POST['enable_fingerprinting']),
			'inspect_json_body'              => !empty($_POST['inspect_json_body']),
			'inspect_multipart_body'         => !empty($_POST['inspect_multipart_body']),
			'enable_behavioral_analysis'     => !empty($_POST['enable_behavioral_analysis']),
			'enable_ai_crawler_control'      => !empty($_POST['enable_ai_crawler_control']),
			'enable_client_hints_validation' => !empty($_POST['enable_client_hints_validation']),
			'enable_agentic_detection'       => !empty($_POST['enable_agentic_detection']),
			'enable_dynamic_ip_ranges'       => !empty($_POST['enable_dynamic_ip_ranges']),
		];

		$write = bb2_write_settings($engine, $new_settings);

		if (!$write['success'])
		{
			return [
				'success' => false,
				'error'   => $write['error'],
				'payload' => $new_settings,
			];
		}

		return ['success' => true, 'file' => $write['file']];
	}

