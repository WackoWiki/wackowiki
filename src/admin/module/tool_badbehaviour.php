	function bb2_write_settings($engine, array $settings): array
	{
		// Strip adapter-only keys (not part of bb_config.php schema)
		unset($settings['adapter'], $settings['log_table']);

		$config_dir = defined('CONFIG_DIR') ? CONFIG_DIR : 'config';

		if (!is_dir($config_dir))
		{
			@mkdir($config_dir, 0755, true);
		}

		if (!is_writable($config_dir))
		{
			return ['success' => false, 'error' => "Config directory not writable: {$config_dir}"];
		}

		// CRITICAL: must match what Configuration::from_file() reads.
		$file = $config_dir . '/bb_config.php';

		$header = "<?php\n"
			. "/**\n"
				. " * Bad Behaviour configuration\n"
					. " * Generated by WackoWiki admin module — " . date('c') . "\n"
						. " * DO NOT EDIT WHILE THE ADMIN UI IS OPEN — changes will be overwritten.\n"
							. " */\n\n"
								. "return " . var_export($settings, true) . ";\n";

								// Atomic write
								$tmp = $file . '.tmp.' . bin2hex(random_bytes(4));
								$bytes = @file_put_contents($tmp, $header, LOCK_EX);

								if ($bytes === false)
								{
									$err = error_get_last();

									return ['success' => false, 'error' => "Failed to write temp: {$tmp} — " . ($err['message'] ?? 'unknown')];
								}

								if (!@rename($tmp, $file))
								{
									@unlink($tmp);
									$err = error_get_last();

									return ['success' => false, 'error' => "Failed to rename → {$file} — " . ($err['message'] ?? 'unknown')];
								}

								@chmod($file, 0644);

								return ['success' => true, 'file' => $file, 'bytes' => $bytes];
	}

