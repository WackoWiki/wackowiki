	// Replace bb2_get_response() with ResultCode enum
	function bb2_get_response($key)
	{
		try {
			$code = ResultCode::from($key);
			return [
				'response'    => $code->http_status(),
				'explanation' => $code->getMessage() ?? '',
				'log'         => $code->value,
			];
		} catch (\ValueError $e) {
			// Legacy 2.x hex or unknown
			return ['response' => 403, 'explanation' => 'Unknown error', 'log' => $key];
		}
	}

